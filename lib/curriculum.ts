export type Level = (typeof LEVELS)[number];

/**
 * 탐구 유형 분류. 검색 필터의 패싯으로 쓴다.
 * `style`은 주제마다 거의 고유해(36개 중 35종) 필터로 쓸 수 없어 따로 둔다.
 */
export const TOPIC_KINDS = [
  '실험·측정',
  '코딩·시뮬레이션',
  '자료·조사',
  '증명·논증',
  '설계·모델링',
  '융합 탐구',
] as const;
export type TopicKind = (typeof TOPIC_KINDS)[number];

/** 대단원 식별자. 라우트 첫 번째 세그먼트이자 아이콘·색상 맵의 키. */
export type UnitId = 'geometry' | 'logic' | 'functions';

/** 대단원별 색조. 실제 색값은 `lib/tone.ts`가 갖는다. */
export type Tone = 'blue' | 'purple' | 'orange';

export type Topic = {
  /** 소단원 안에서 유일. 앵커 링크(`#id`)와 React key에 쓴다. */
  id: string;
  title: string;
  summary: string;
  question: string;
  method: string;
  career: string;
  curriculum: string;
  level: Level;
  /** 화면에 그대로 보여주는 유형 라벨. 필터에는 쓰지 않는다. */
  style: string;
  /** 필터용 분류. */
  kind: TopicKind;
};

export type Subunit = {
  /** 라우트 두 번째 세그먼트. 사이트 전체에서 유일해야 한다. */
  id: string;
  label: string;
  official: string;
  standard: string;
  intro: string;
  note?: string;
  topics: Topic[];
};

export type CurriculumUnit = {
  id: UnitId;
  roman: string;
  title: string;
  shortTitle: string;
  description: string;
  tone: Tone;
  subunits: Subunit[];
};

